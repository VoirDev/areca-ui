/**
 * Writes `IconCatalogue.kt`: one `IconItem` per icon `:standalone:icons` declares, read from its mapping.
 *
 * Kotlin Multiplatform has no reflection to enumerate the `ArecaIcons` extension properties, so the Icons
 * showcase lists the whole set from this generated file instead of a hand-kept copy of the names.
 */
abstract class GenerateIconCatalogue : DefaultTask() {

    /** `standalone/icons/icons.tsv`; the first column of every non-comment row is an icon name. */
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val mapping: RegularFileProperty

    /** Kotlin source root the catalogue is written under. */
    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    /** Rewrites the catalogue from the mapping. */
    @TaskAction
    fun generate() {
        val names = mapping.get().asFile.readLines()
            .filter { it.isNotBlank() && !it.startsWith("#") }
            .map { it.substringBefore('\t') }
            .sorted()
        val directory = outputDirectory.get().asFile.resolve("dev/voir/areca/playground/foundation/icon")
        directory.deleteRecursively()
        directory.mkdirs()
        directory.resolve("IconCatalogue.kt").writeText(
            buildString {
                appendLine("// Generated by the playground's `generateIconCatalogue` task from standalone/icons/icons.tsv.")
                appendLine("package dev.voir.areca.playground.foundation.icon")
                appendLine()
                appendLine("import dev.voir.areca.icons.*")
                appendLine()
                appendLine("/** Every icon in `ArecaIcons`, sorted by name. */")
                appendLine("internal val arecaIconCatalogue: List<IconItem> = listOf(")
                names.forEach { appendLine("    IconItem(\"$it\", ArecaIcons.$it),") }
                appendLine(")")
            },
        )
    }
}

val generateIconCatalogue = tasks.register<GenerateIconCatalogue>("generateIconCatalogue") {
    description = "Generates the Icons showcase's list of every icon from standalone/icons/icons.tsv."
    mapping.set(rootProject.layout.projectDirectory.file("standalone/icons/icons.tsv"))
    outputDirectory.set(layout.buildDirectory.dir("generated/iconCatalogue/kotlin"))
}

